import { describe, expect, it } from 'vitest';
import { existsSync, readFileSync } from 'fs';
import { resolve } from 'path';
import {
  buildProductShareText,
  buildStoreShareText,
  buildWhatsAppHttpsUrl,
  buildWhatsAppSchemeUrl,
  productShareUrl,
  storeShareUrl,
} from '@/lib/sociva-share';

const read = (rel: string) => readFileSync(resolve(process.cwd(), rel), 'utf8');

describe('sociva-share', () => {
  it('builds product WhatsApp-friendly text with link', () => {
    const text = buildProductShareText({
      name: 'Chicken Biryani',
      priceLabel: '₹199',
      sellerName: 'Mountain Studio Cafe',
      url: 'https://www.sociva.in/api/share/product/abc',
    });
    expect(text).toContain('Found this on Sociva');
    expect(text).toContain('Chicken Biryani - ₹199');
    expect(text).toContain('Mountain Studio Cafe');
    expect(text).toContain('https://www.sociva.in/api/share/product/abc');
  });

  it('builds store share text', () => {
    const text = buildStoreShareText({
      storeName: 'Biryani and Kebab',
      url: 'https://www.sociva.in/api/share/store/xyz',
    });
    expect(text).toContain('Biryani and Kebab');
    expect(text).toContain('/api/share/store/xyz');
  });

  it('uses path-based OG share URLs (not hash-only)', () => {
    expect(productShareUrl('p1')).toMatch(/\/api\/share\/product\/p1(\?|$)/);
    expect(storeShareUrl('s1')).toMatch(/\/api\/share\/store\/s1(\?|$)/);
    expect(productShareUrl('p1')).not.toContain('#/');
  });

  it('product detail share no longer calls hooks inside click handlers', () => {
    const src = require('fs').readFileSync(
      require('path').resolve(__dirname, '../components/product/ProductDetailSheet.tsx'),
      'utf8',
    );
    expect(src).toMatch(/shareSocivaContent/);
    expect(src).not.toMatch(/useFeedbackPopup\(\)/);
    expect(src).toMatch(/d\.setReportOpen\(true\)/);
    expect(src).toMatch(/navigate\('\/auth'/);
    expect(src).not.toMatch(/onOpenChange\(false\);\s*d\.setReportOpen/);
  });

  it('encodes product name, price, punctuation, emoji and the share URL into the WhatsApp scheme', () => {
    const text = buildProductShareText({
      name: 'Mom\'s "Fish & Chips" 🔥',
      priceLabel: '₹199',
      sellerName: 'KHATMITTHI',
      url: 'https://www.sociva.in/api/share/product/abc?og=1',
    });
    const scheme = buildWhatsAppSchemeUrl(text);
    const https = buildWhatsAppHttpsUrl(text);
    expect(scheme.startsWith('whatsapp://send?text=')).toBe(true);
    expect(https.startsWith('https://wa.me/?text=')).toBe(true);
    expect(scheme).not.toContain('api.whatsapp.com');
    expect(https).not.toContain('api.whatsapp.com/send');
    const decoded = decodeURIComponent(scheme.slice('whatsapp://send?text='.length));
    expect(decoded).toBe(text);
    expect(decoded).toContain('Mom\'s "Fish & Chips" 🔥');
    expect(decoded).toContain('₹199');
    expect(decoded).toContain('https://www.sociva.in/api/share/product/abc?og=1');
    expect(scheme).toContain('%0A');
    expect(scheme).toContain('%26');
  });

  it('share helper opens WhatsApp via the native scheme and keeps Share as fallback', () => {
    const src = require('fs').readFileSync(
      require('path').resolve(__dirname, '../lib/sociva-share.ts'),
      'utf8',
    );
    expect(src).toMatch(/whatsapp:\/\/send\?text=/);
    expect(src).toMatch(/@capacitor\/share/);
    expect(src).toMatch(/@capacitor\/clipboard/);
    expect(src).not.toMatch(/@capacitor\/browser/);
    expect(src).not.toMatch(/Browser\.open/);
    expect(src).not.toMatch(/api\.whatsapp\.com/);
    expect(src).toMatch(/console\.error\('\[sociva-share\] Capacitor Share failed'/);
    expect(src).toMatch(/name: 'AbortError'/);
    expect(src).toMatch(/return 'failed'/);
  });

  it('declares WhatsApp URL scheme visibility on Android and iOS', () => {
    const cap = read('capacitor.config.ts');
    const manifest = read('android/app/src/main/AndroidManifest.xml');
    expect(cap).toMatch(/'whatsapp'/);
    expect(manifest).toContain('com.whatsapp');
    expect(manifest).toContain('com.whatsapp.w4b');
    expect(manifest).toMatch(/android:scheme="whatsapp"/);
  });

  it('registers Share and Clipboard in the Android project', () => {
    const settings = read('android/capacitor.settings.gradle');
    const build = read('android/app/capacitor.build.gradle');
    expect(settings).toContain("include ':capacitor-share'");
    expect(settings).toContain("include ':capacitor-clipboard'");
    expect(build).toContain("implementation project(':capacitor-share')");
    expect(build).toContain("implementation project(':capacitor-clipboard')");
    // Generated by `npx cap update android` and gitignored. Assert it when present.
    const pluginsPath = resolve(process.cwd(), 'android/app/src/main/assets/capacitor.plugins.json');
    if (existsSync(pluginsPath)) {
      const plugins = readFileSync(pluginsPath, 'utf8');
      expect(plugins).toContain('"pkg": "@capacitor/share"');
      expect(plugins).toContain('"pkg": "@capacitor/clipboard"');
    }
  });
});
